/**
 * Canonical Permission Matrix description for documentation & auditing (GAR-003 §10, GAR-049)
 */
export interface PermissionMatrixEntry {
  role: string;
  roleType: 'ORGANIZATION' | 'PLATFORM';
  permission: CanonicalPermission;
  resourceScope: string;
  condition: string;
  deniedCondition: string;
}

export function getCanonicalPermissionMatrix(): PermissionMatrixEntry[] {
  const matrix: PermissionMatrixEntry[] = [];

  for (const [role, permissions] of Object.entries(ROLE_PERMISSIONS)) {
    for (const perm of permissions) {
      matrix.push({
        role,
        roleType: 'ORGANIZATION',
        permission: perm,
        resourceScope: 'ORGANIZATION_SCOPED',
        condition: 'Active membership in active organization',
        deniedCondition: 'Suspended/revoked membership, suspended organization, cross-tenant resource',
      });
    }
  }

  for (const [role, permissions] of Object.entries(PLATFORM_ROLE_PERMISSIONS)) {
    for (const perm of permissions) {
      matrix.push({
        role,
        roleType: 'PLATFORM',
        permission: perm,
        resourceScope: 'GLOBAL_PLATFORM',
        condition: 'Assigned platform role with active account status',
        deniedCondition: 'Suspended/locked account or missing platform role',
      });
    }
  }

  return matrix;
}
