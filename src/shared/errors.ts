export interface ErrorDetail {
  field?: string;
  message: string;
  code?: string;
}

export interface CanonicalErrorPayload {
  code: ErrorCode;
  message: string;
  requestId: string;
  details?: ErrorDetail[];
  path?: string;
  timestamp: string;
}

export class CanonicalAppError extends Error {
  public readonly code: ErrorCode;
  public readonly statusCode: number;
  public readonly details?: ErrorDetail[];

  constructor(code: ErrorCode, message: string, statusCode?: number, details?: ErrorDetail[]) {
    super(message);
    this.name = 'CanonicalAppError';
    this.code = code;
    this.details = details;

    if (statusCode) {
      this.statusCode = statusCode;
    } else {
      switch (code) {
        case ErrorCode.VALIDATION_ERROR:
        case ErrorCode.FUEL_INVALID_QUANTITY:
        case ErrorCode.FUEL_INVALID_ODOMETER:
        case ErrorCode.VEHICLE_EXPENSE_INVALID_AMOUNT:
        case ErrorCode.VEHICLE_EXPENSE_INVALID_CURRENCY:
        case ErrorCode.RECURRING_EXPENSE_INVALID_FREQUENCY:
        case ErrorCode.VEHICLE_TYRE_INVALID_SIZE:
        case ErrorCode.VEHICLE_TYRE_ROTATION_INVALID:
        case ErrorCode.COMPONENT_WARRANTY_INVALID:
        case ErrorCode.VEHICLE_MODIFICATION_INVALID:
        case ErrorCode.ROADSIDE_LOCATION_INVALID:
        case ErrorCode.ROADSIDE_LOCATION_REQUIRED:
        case ErrorCode.ROADSIDE_TRIAGE_REQUIRED:
        case ErrorCode.ROADSIDE_INTERVENTION_INVALID:
          this.statusCode = 400;
          break;
        case ErrorCode.NOT_AUTHORIZED:
        case ErrorCode.VEHICLE_TIMELINE_ACCESS_DENIED:
        case ErrorCode.VEHICLE_TIMELINE_CORRECTION_NOT_ALLOWED:
        case ErrorCode.VEHICLE_PASSPORT_ACCESS_DENIED:
        case ErrorCode.FUEL_ENTRY_ACCESS_DENIED:
        case ErrorCode.VEHICLE_EXPENSE_ACCESS_DENIED:
        case ErrorCode.VEHICLE_COMPONENT_ACCESS_DENIED:
        case ErrorCode.VEHICLE_TYRE_ACCESS_DENIED:
        case ErrorCode.ROADSIDE_INCIDENT_ACCESS_DENIED:
        case ErrorCode.ROADSIDE_PROVIDER_NOT_ELIGIBLE:
          this.statusCode = 403;
          break;
        case ErrorCode.NOT_FOUND_OR_NOT_ACCESSIBLE:
        case ErrorCode.RESOURCE_NOT_FOUND:
        case ErrorCode.VEHICLE_TIMELINE_ENTRY_NOT_FOUND:
        case ErrorCode.VEHICLE_PASSPORT_NOT_AVAILABLE:
        case ErrorCode.FUEL_ENTRY_NOT_FOUND:
        case ErrorCode.VEHICLE_EXPENSE_NOT_FOUND:
        case ErrorCode.VEHICLE_COMPONENT_NOT_FOUND:
        case ErrorCode.VEHICLE_TYRE_NOT_FOUND:
        case ErrorCode.ROADSIDE_INCIDENT_NOT_FOUND:
        case ErrorCode.ROADSIDE_PROVIDER_OFFER_NOT_FOUND:
        case ErrorCode.ROADSIDE_ASSIGNMENT_NOT_FOUND:
          this.statusCode = 404;
          break;
        case ErrorCode.BUSINESS_RULE_VIOLATION:
        case ErrorCode.FUEL_INCOMPATIBLE_TYPE:
        case ErrorCode.FUEL_ECONOMY_INSUFFICIENT_DATA:
        case ErrorCode.COST_OF_OWNERSHIP_INSUFFICIENT_DATA:
        case ErrorCode.VEHICLE_COMPONENT_INVALID_REPLACEMENT:
        case ErrorCode.ROADSIDE_EMERGENCY_ROUTE_REQUIRED:
        case ErrorCode.ROADSIDE_ASSISTANCE_NOT_AVAILABLE:
        case ErrorCode.ROADSIDE_TOW_REQUIRED:
          this.statusCode = 422;
          break;
        case ErrorCode.INVALID_STATE:
        case ErrorCode.INVALID_STATE_TRANSITION:
        case ErrorCode.CONFLICT:
        case ErrorCode.VEHICLE_TIMELINE_ENTRY_SUPERSEDED:
        case ErrorCode.VEHICLE_COMPONENT_ALREADY_REMOVED:
        case ErrorCode.VEHICLE_COMPONENT_POSITION_CONFLICT:
        case ErrorCode.VEHICLE_TYRE_POSITION_OCCUPIED:
        case ErrorCode.VEHICLE_TYRE_ALREADY_REMOVED:
        case ErrorCode.ROADSIDE_INCIDENT_INVALID_STATE:
        case ErrorCode.ROADSIDE_PROVIDER_OFFER_EXPIRED:
        case ErrorCode.ROADSIDE_PROVIDER_OFFER_ALREADY_RESOLVED:
        case ErrorCode.ROADSIDE_ASSIGNMENT_EXISTS:
        case ErrorCode.ROADSIDE_ASSIGNMENT_INVALID_STATE:
          this.statusCode = 409;
          break;
        case ErrorCode.VEHICLE_PASSPORT_SHARE_EXPIRED:
        case ErrorCode.VEHICLE_PASSPORT_SHARE_REVOKED:
          this.statusCode = 410;
          break;
        case ErrorCode.VEHICLE_PASSPORT_SHARE_INVALID:
          this.statusCode = 400;
          break;
        case ErrorCode.RATE_LIMITED:
          this.statusCode = 429;
          break;
        case ErrorCode.DEPENDENCY_UNAVAILABLE:
          this.statusCode = 503;
          break;
        case ErrorCode.SAFETY_REVIEW_REQUIRED:
          this.statusCode = 422;
          break;
        case ErrorCode.INTERNAL_ERROR:
        default:
          this.statusCode = 500;
          break;
      }
    }
  }
}
